const CDN_BASE = process.env.NEXT_PUBLIC_CDN_URL ?? "http://localhost:3000";
const SHORT_BASE = process.env.NEXT_PUBLIC_SHORT_URL ?? "http://localhost:3000";
const DL_BASE = process.env.NEXT_PUBLIC_DL_URL ?? "http://localhost:3000";

function joinUrl(base: string, path: string): string {
  return `${base.replace(/\/+$/, "")}/${path.replace(/^\/+/, "")}`;
}

function isLocalBase(base: string): boolean {
  try {
    const host = new URL(base).hostname;
    return host === "localhost" || host === "127.0.0.1" || host === "::1";
  } catch {
    return false;
  }
}

/**
 * Only same-origin paths are safe to navigate to. "//evil.com" and "/\evil.com"
 * both start with a slash but resolve to another origin.
 */
export function safeRedirectPath(value: string | null | undefined, fallback: string): string {
  if (!value || !value.startsWith("/")) {
    return fallback;
  }

  if (value.startsWith("//") || value.startsWith("/\\")) {
    return fallback;
  }

  return value;
}

export function getHostname(host: string | null): string {
  return (host ?? "").split(":")[0]?.toLowerCase() ?? "";
}

export function buildCdnUrl(fileKey: string): string {
  return joinUrl(CDN_BASE, fileKey);
}

export function buildShortUrl(slug: string): string {
  const path = isLocalBase(SHORT_BASE) ? `r/${encodeURIComponent(slug)}` : slug;
  return joinUrl(SHORT_BASE, path);
}

export function buildDlUrl(fileId: string): string {
  const path = isLocalBase(DL_BASE) ? `d/${fileId}` : fileId;
  return joinUrl(DL_BASE, path);
}

/**
 * True when the URL already points at one of our own hosts. Share targets are
 * generated by us, so they must not be rejected by the SSRF guard that protects
 * user supplied short-link destinations.
 */
export function isOwnHost(url: URL): boolean {
  const bases = [CDN_BASE, SHORT_BASE, DL_BASE, process.env.APP_URL ?? ""];

  return bases.some((base) => {
    if (!base) {
      return false;
    }

    try {
      return new URL(base).host === url.host;
    } catch {
      return false;
    }
  });
}
